/* ============================================================
   5. TRIGGERS
   5.1 last_update automatico (equivale a ON UPDATE CURRENT_TIMESTAMP de MySQL)
   5.2 Registro de operaciones en tb_logs (trazabilidad)
   ============================================================ */
CREATE OR REPLACE FUNCTION fn_set_last_update() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  NEW.last_update := CURRENT_TIMESTAMP;
  RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION fn_log_operation() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_row  jsonb;
  v_op   log_operation;
  v_desc text;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_op := 'Create'; v_row := to_jsonb(NEW) - 'password';
    v_desc := format('Insercion en %s: %s', TG_TABLE_NAME, v_row::text);
  ELSIF TG_OP = 'UPDATE' THEN
    v_op := 'Update'; v_row := to_jsonb(NEW) - 'password';
    v_desc := format('Actualizacion en %s: antes=%s | despues=%s', TG_TABLE_NAME, (to_jsonb(OLD) - 'password')::text, v_row::text);
  ELSE
    v_op := 'Delete'; v_row := to_jsonb(OLD) - 'password';
    v_desc := format('Eliminacion en %s: %s', TG_TABLE_NAME, v_row::text);
  END IF;

  INSERT INTO tb_logs (table_name, operation, db_user, description)
  VALUES (TG_TABLE_NAME, v_op,
          session_user || '@' || COALESCE(host(inet_client_addr()), 'local'),
          v_desc);
  RETURN NULL;
END $$;

DO $$
DECLARE t text;
BEGIN
  FOR t IN SELECT table_name FROM information_schema.columns
           WHERE table_schema = 'public' AND column_name = 'last_update'
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_last_update ON %1$I', t);
    EXECUTE format('CREATE TRIGGER trg_%1$s_last_update BEFORE UPDATE ON %1$I FOR EACH ROW EXECUTE FUNCTION fn_set_last_update()', t);
  END LOOP;

  FOR t IN SELECT table_name FROM information_schema.tables
           WHERE table_schema = 'public' AND table_type = 'BASE TABLE' AND table_name <> 'tb_logs'
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_%1$s_log ON %1$I', t);
    EXECUTE format('CREATE TRIGGER trg_%1$s_log AFTER INSERT OR UPDATE OR DELETE ON %1$I FOR EACH ROW EXECUTE FUNCTION fn_log_operation()', t);
  END LOOP;
END $$;

