CREATE OR REPLACE FUNCTION sp_register_user_with_person(
  p_email VARCHAR, p_nickname VARCHAR, p_password VARCHAR,
  p_courtesy_title VARCHAR, p_given_names VARCHAR, p_family_names VARCHAR,
  p_birth_date DATE, p_gender_id SMALLINT, p_country_code CHAR, p_phone VARCHAR
) RETURNS INTEGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_user_id INTEGER;
BEGIN
  INSERT INTO tb_users (email, nickname, password)
  VALUES (p_email, p_nickname, md5(p_password)) RETURNING id INTO v_user_id;

  INSERT INTO tb_people (user_id, courtesy_title, given_names, family_names, birth_date, gender_id, country_code, phone)
  VALUES (v_user_id, p_courtesy_title, p_given_names, p_family_names, p_birth_date, p_gender_id, p_country_code, p_phone);
  RETURN v_user_id;
END $$;

CREATE OR REPLACE FUNCTION sp_soft_delete_user(p_user_id INTEGER) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT (pg_has_role(session_user, 'superadmin', 'member') OR pg_has_role(session_user, 'admin', 'member')
          OR pg_has_role(session_user, 'support', 'member')) THEN
    RAISE EXCEPTION 'Acceso denegado: rol no autorizado';
  END IF;
  UPDATE tb_users SET status = FALSE WHERE id = p_user_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Usuario % no existe', p_user_id; END IF;
END $$;

CREATE OR REPLACE FUNCTION sp_soft_delete_product(p_product_id INTEGER) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT (pg_has_role(session_user, 'superadmin', 'member') OR pg_has_role(session_user, 'admin', 'member')
          OR pg_has_role(session_user, 'support', 'member')) THEN
    RAISE EXCEPTION 'Acceso denegado: rol no autorizado';
  END IF;
  UPDATE tb_products SET status = FALSE WHERE id = p_product_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Producto % no existe', p_product_id; END IF;
END $$;

CREATE OR REPLACE FUNCTION sp_restore_product(p_product_id INTEGER) RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF NOT (pg_has_role(session_user, 'superadmin', 'member') OR pg_has_role(session_user, 'admin', 'member')
          OR pg_has_role(session_user, 'support', 'member')) THEN
    RAISE EXCEPTION 'Acceso denegado: rol no autorizado';
  END IF;
  UPDATE tb_products SET status = TRUE WHERE id = p_product_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Producto % no existe', p_product_id; END IF;
END $$;

