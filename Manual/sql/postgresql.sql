DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'log_operation') THEN
    CREATE TYPE log_operation AS ENUM ('Create','Read','Update','Delete');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'fulfillment_status') THEN
    CREATE TYPE fulfillment_status AS ENUM ('Pending','Accepted','Preparing','Sent','Delivered','Canceled','Returned');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'type_ownership') THEN
    CREATE TYPE type_ownership AS ENUM ('Owner','Reseller','Distributor');
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS tb_users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email         VARCHAR(80)  NOT NULL UNIQUE,
  nickname      VARCHAR(100) NOT NULL UNIQUE,
  password      VARCHAR(255) NOT NULL,
  creation_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_update   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  last_login    TIMESTAMP,
  status        BOOLEAN NOT NULL DEFAULT TRUE
);

